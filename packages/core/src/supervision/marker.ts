/**
 * Runtime marker storage: atomic write, defensive read, and stale transfer.
 *
 * Ownership: this module owns marker storage and the marker lifecycle. It is
 * deliberately free of policy: it does not decide whether an old engine may be
 * killed and it does not delete a token file. It only turns a marker directory
 * into marker records, or refuses to.
 *
 * Atomicity matters because a crash can land between the write and the rename.
 * Every write goes to a sibling `*.tmp` first, so a reader sees either the old
 * complete file or the new complete file, never a half-written JSON document.
 *
 * Reading is defensive because the input is a file a previous run (or the user)
 * could have damaged. A corrupt or malformed marker must never crash start-up;
 * it comes back as a typed failure so the caller can log it and continue with a
 * normal boot.
 */

import { readFile, readdir, rename, unlink, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";

import type { EngineMarker, ProcessEvidence, RuntimeMarker, StaleEngineRecord } from "./types";

/** Fixed marker name inside the caller-provided directory (userData in the shell). */
export const RUNTIME_MARKER_FILE_NAME = "runtime.json";

/** Prefix of a kept ambiguous marker; the instance id makes the name unique. */
export const STALE_MARKER_PREFIX = "runtime-stale-";

/** Suffix shared by runtime and stale marker files. */
export const STALE_MARKER_SUFFIX = ".json";

/** Temporary sibling used by every atomic write; renamed onto the final name. */
const TEMP_SUFFIX = ".tmp";

/** Owner-only permissions on POSIX; the marker carries a local run token. */
const MARKER_FILE_MODE = 0o600;

/** Cap for a diagnostic string copied into `MarkerReadResult.detail`. */
const DETAIL_LIMIT = 300;

/** Accepted file names for `listStale` and `removeStale`. */
const STALE_FILE_PATTERN = /^runtime-stale-.+\.json$/;

/**
 * Why reading failed.
 *
 * `missing` is the normal first-boot case. `corrupt` is unparseable JSON,
 * `invalid` is parseable JSON of the wrong shape, and `unreadable` is an I/O
 * failure other than absence (permissions, a directory in the way, ...).
 */
export type MarkerReadFailureReason = "missing" | "corrupt" | "invalid" | "unreadable";

/** Result of {@link readRuntimeMarker}: a marker or a reason, never an exception. */
export type MarkerReadResult =
  | { readonly ok: true; readonly marker: RuntimeMarker }
  | {
      readonly ok: false;
      readonly reason: MarkerReadFailureReason;
      readonly detail?: string;
    };

/** One stale file found by {@link listStale}. */
export type StaleMarkerEntry = {
  /** Absolute path of the stale file. */
  readonly path: string;
  /** Parsed record, or `null` when the file was damaged. */
  readonly record: StaleEngineRecord | null;
  /** Parse failure when `record` is `null`; always `null` on success. */
  readonly detail: string | null;
};

/** Absolute path of `<dir>/runtime.json`. */
export function runtimeMarkerPath(dir: string): string {
  return resolve(dir, RUNTIME_MARKER_FILE_NAME);
}

/**
 * File name for a kept marker.
 *
 * The instance id is generated by the shell today, but it arrives from a file a
 * different run wrote, so it is sanitized rather than trusted: a value such as
 * `../../outside` must not turn into a path escape. The sanitized name is
 * deterministic, which is what makes the round-trip through `listStale` and
 * `removeStale` possible without storing a second index.
 */
export function staleMarkerFileName(instanceId: string): string {
  const safe = instanceId.replace(/[^A-Za-z0-9_-]/g, "_").slice(0, 80);
  return `${STALE_MARKER_PREFIX}${safe === "" ? "unknown" : safe}${STALE_MARKER_SUFFIX}`;
}

/** Absolute path of the stale file for `instanceId`. */
export function staleMarkerPath(dir: string, instanceId: string): string {
  return resolve(dir, staleMarkerFileName(instanceId));
}

/**
 * Read `<dir>/runtime.json`.
 *
 * Never rejects for a missing, corrupt or malformed file: those are expected
 * states at start-up, and turning them into exceptions would force every caller
 * to duplicate the same try/catch. A genuinely unreadable file is also reported
 * as a value; only a programming error can throw here.
 */
export async function readRuntimeMarker(dir: string): Promise<MarkerReadResult> {
  const filePath = runtimeMarkerPath(dir);

  let raw: string;
  try {
    raw = await readFile(filePath, "utf8");
  } catch (error) {
    if (isMissingFileError(error)) {
      return { ok: false, reason: "missing" };
    }

    return failure("unreadable", summarizeError(error));
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    return failure("corrupt", summarizeError(error));
  }

  if (!isRuntimeMarker(parsed)) {
    return failure("invalid", "runtime marker does not match schemaVersion 1");
  }

  return { ok: true, marker: parsed };
}

/**
 * Atomically replace `<dir>/runtime.json` with `marker` and return its path.
 *
 * A write failure is thrown on purpose: without a marker this shell's engine
 * would be invisible to the next start-up, so the caller has to know. Validation
 * happens first so a shape bug is a local TypeError instead of a file that every
 * later boot reports as `invalid`.
 */
export async function writeRuntimeMarker(dir: string, marker: RuntimeMarker): Promise<string> {
  if (!isRuntimeMarker(marker)) {
    throw new TypeError("runtime marker does not match schemaVersion 1");
  }

  const filePath = runtimeMarkerPath(dir);
  await writeJsonAtomic(filePath, marker);
  return filePath;
}

/**
 * Delete `<dir>/runtime.json`.
 *
 * Absence is not an error: a previous cleanup attempt may have won the race, or
 * this is a first boot. This is a single unlink of one known name, never a
 * recursive delete.
 */
export async function clearRuntimeMarker(dir: string): Promise<void> {
  await unlinkIfPresent(runtimeMarkerPath(dir));
}

/**
 * Keep `record` as `runtime-stale-<instanceId>.json`, then remove the live marker.
 *
 * The stale file is written first. If the process dies in between, the record is
 * already durable and the live marker is merely duplicated; the reverse order
 * would lose the only copy of a marker that could not be reclaimed.
 */
export async function moveToStale(dir: string, record: StaleEngineRecord): Promise<string> {
  if (!isStaleEngineRecord(record)) {
    throw new TypeError("stale engine record does not match schemaVersion 1");
  }

  const filePath = staleMarkerPath(dir, record.marker.instanceId);
  await writeJsonAtomic(filePath, record);
  await clearRuntimeMarker(dir);
  return filePath;
}

/**
 * List kept markers in `dir`.
 *
 * A damaged stale file is still listed, with `record: null` and a detail, so the
 * caller can show it and let the user delete it instead of leaving an invisible
 * file behind forever. A missing directory is an empty list: start-up often runs
 * before userData exists.
 */
export async function listStale(dir: string): Promise<StaleMarkerEntry[]> {
  let names: string[];
  try {
    names = await readdir(dir);
  } catch (error) {
    if (isMissingFileError(error)) {
      return [];
    }

    throw error;
  }

  const candidates = names.filter((name) => STALE_FILE_PATTERN.test(name)).sort();
  const entries: StaleMarkerEntry[] = [];

  for (const name of candidates) {
    const filePath = resolve(dir, name);
    const parsed = await readStaleRecord(filePath);
    entries.push({ path: filePath, record: parsed.record, detail: parsed.detail });
  }

  return entries;
}

/**
 * Delete one stale file by name and report whether it existed.
 *
 * The name is validated as a bare stale-marker file name before anything is
 * unlinked. That is the guard that keeps a caller bug (or a path from an
 * untrusted source) from turning this into an arbitrary-file delete.
 */
export async function removeStale(dir: string, fileName: string): Promise<boolean> {
  if (basename(fileName) !== fileName || !STALE_FILE_PATTERN.test(fileName)) {
    return false;
  }

  try {
    await unlink(resolve(dir, fileName));
    return true;
  } catch (error) {
    if (isMissingFileError(error)) {
      return false;
    }
    throw error;
  }
}

/** Write JSON through a sibling temp file so readers never see a partial document. */
async function writeJsonAtomic(filePath: string, value: unknown): Promise<void> {
  const tempPath = `${filePath}${TEMP_SUFFIX}`;
  try {
    await writeFile(tempPath, `${JSON.stringify(value, null, 2)}\n`, {
      encoding: "utf8",
      mode: MARKER_FILE_MODE,
    });
    await rename(tempPath, filePath);
  } catch (error) {
    // Best effort: a failed write or rename must not leave a stray temp file.
    await unlink(tempPath).catch(() => undefined);
    throw error;
  }
}

/** Remove a file, tolerating absence. */
async function unlinkIfPresent(filePath: string): Promise<void> {
  try {
    await unlink(filePath);
  } catch (error) {
    if (!isMissingFileError(error)) {
      throw error;
    }
  }
}

/** Parse one stale file without throwing; a damaged file becomes `record: null`. */
async function readStaleRecord(
  filePath: string,
): Promise<{ record: StaleEngineRecord | null; detail: string | null }> {
  let raw: string;
  try {
    raw = await readFile(filePath, "utf8");
  } catch (error) {
    return { record: null, detail: `unreadable: ${summarizeError(error)}` };
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    return { record: null, detail: `corrupt: ${summarizeError(error)}` };
  }

  if (!isStaleEngineRecord(parsed)) {
    return { record: null, detail: "invalid: stale engine record does not match schemaVersion 1" };
  }

  return { record: parsed, detail: null };
}

/** Build a typed failure, omitting `detail` so the optional field stays absent. */
function failure(reason: MarkerReadFailureReason, detail: string): MarkerReadResult {
  return { ok: false, reason, detail };
}

/**
 * Shape guard for a runtime marker.
 *
 * It checks the documented fields and their JSON types, not semantic ranges:
 * `startedAt` need not parse as a date here because `decideReclaim` already
 * fails closed on an unparseable timestamp. Rejecting unknown fields would break
 * the forward-compatibility rule, so extras are ignored.
 */
function isRuntimeMarker(value: unknown): value is RuntimeMarker {
  if (!isRecord(value)) {
    return false;
  }

  if (
    value.schemaVersion !== 1 ||
    typeof value.instanceId !== "string" ||
    typeof value.startedAt !== "string" ||
    typeof value.appVersion !== "string"
  ) {
    return false;
  }

  return value.engine === null || isEngineMarker(value.engine);
}

/** Shape guard for the engine half of a marker. */
function isEngineMarker(value: unknown): value is EngineMarker {
  if (!isRecord(value)) {
    return false;
  }

  return (
    typeof value.pid === "number" &&
    Number.isInteger(value.pid) &&
    value.pid > 0 &&
    typeof value.startedAt === "string" &&
    typeof value.exePath === "string" &&
    typeof value.bundlePath === "string" &&
    typeof value.runToken === "string" &&
    (value.watchdog === "active" ||
      value.watchdog === "inactive" ||
      value.watchdog === "unknown") &&
    (value.tokenFile === null || typeof value.tokenFile === "string") &&
    (value.port === null || typeof value.port === "number")
  );
}

/** Shape guard for evidence embedded in a stale record. */
function isProcessEvidence(value: unknown): value is ProcessEvidence {
  if (!isRecord(value)) {
    return false;
  }

  return (
    typeof value.pid === "number" &&
    typeof value.alive === "boolean" &&
    (value.imagePath === null || typeof value.imagePath === "string") &&
    (value.createdAt === null || typeof value.createdAt === "string") &&
    (value.runToken === null || typeof value.runToken === "string") &&
    typeof value.tokenFileExists === "boolean" &&
    typeof value.portListening === "boolean" &&
    typeof value.matched === "boolean" &&
    typeof value.reason === "string"
  );
}

/** Shape guard for a kept marker. */
function isStaleEngineRecord(value: unknown): value is StaleEngineRecord {
  if (!isRecord(value)) {
    return false;
  }

  return (
    value.schemaVersion === 1 &&
    typeof value.detectedAt === "string" &&
    isRuntimeMarker(value.marker) &&
    isProcessEvidence(value.evidence) &&
    typeof value.reason === "string"
  );
}

/** Narrow an unknown JSON value to a plain object. */
function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** True when the error is the platform's "file does not exist" signal. */
function isMissingFileError(error: unknown): boolean {
  return (
    typeof error === "object" && error !== null && (error as { code?: unknown }).code === "ENOENT"
  );
}

/** One compact, capped line for a stored diagnostic. */
function summarizeError(error: unknown): string {
  const message =
    typeof error === "object" && error !== null && "message" in error
      ? String((error as { message: unknown }).message)
      : String(error);
  const compact = message.replace(/\s+/g, " ").trim();

  return compact.length > DETAIL_LIMIT ? `${compact.slice(0, DETAIL_LIMIT)}...` : compact;
}
